# 五、自测
# ============================================================
if __name__ == "__main__":
    V, P_AGC = gen_data()
    print("【模拟数据】")
    print(f"  风速范围: [{V.min():.2f}, {V.max():.2f}] m/s")
    print(f"  电网调度指令: {P_AGC} MW")
    print(f"  平均分配时单机功率: {P_AGC/N:.2f} MW")
    print(f"  约束③允许区间: [{P_AGC/N-DELTA:.2f}, {P_AGC/N+DELTA:.2f}] MW")
    print(f"  约束②上限: {P_RATED} MW  →  "
          f"{'✅ 可行' if P_AGC/N+DELTA <= P_RATED else '❌ 不可行'}")

    P_test = np.full(N, P_AGC / N)
    d1 = damage_spindle(P_test, V)
    d2 = damage_tower(P_test, V)
    print(f"\n【平均分配下的损伤（前5台）】")
    print(f"  主轴: {d1[:5]}")
    print(f"  塔架: {d2[:5]}")
    print(f"  主轴平均: {d1.mean():.6f}   塔架平均: {d2.mean():.6f}")
