"""
================================================================
A题 Q3 复现 · 第1步：数据与损伤模型
================================================================
【本文件干什么】
  1. 造模拟数据（风速 V、电网调度指令 P_AGC）——真实版从附件2读取
  2. 定义损伤模型（主轴损伤 / 塔架损伤）——真实版接 Q1 雨流模型

【为什么单独成模块】
  题目里 Q3 依赖 Q1（损伤度量）和 Q2（载荷估算）。
  咱们没拿到附件，所以这里用"物理上合理的替代模型"。
  真实版只需替换下面两个函数体，其余代码一个字不用改。
================================================================
"""

import numpy as np

# ============================================================
# 一、常量参数（题目给定，不可改）
# ============================================================
N = 100              # 风机台数（题目：以 N=100 为例）
P_RATED = 5.0        # 单机额定功率 (MW)（题目给定）
V_RATED = 11.2       # 额定风速 (m/s)（题目给定）
DELTA = 1.0          # 偏离平均分配的最大差值 (MW)（题目给定）

# 风速范围：题目注"本题提供的数据均为风能过剩的情形，即风速超过额定风速"
V_MIN, V_MAX = 11.2, 15.0


# ============================================================
# 二、模拟数据生成（真实版：从附件2读取）
# ============================================================
def gen_data(seed=42):
    """
    生成模拟数据。

    返回
    ----
    V     : (N,) 各风机轮毂处等效风速 (m/s)
    P_AGC : float 电网调度指令，全场总功率 (MW)

    真实版替换为：
        df = pd.read_excel("../附件2.xlsx")
        V = df["轮毂处等效风速"].values
        P_AGC = df["电网有功调度指令"].values[t]
    """
    rng = np.random.default_rng(seed)
    V = rng.uniform(V_MIN, V_MAX, N)

    # 调度指令：设定为全场额定容量的某个比例（风能过剩场景）
    # 注意：约束③要求 |P_i - P_AGC/N| <= 1，且 P_i <= 5
    #       => 必须 P_AGC/N + 1 <= 5  =>  P_AGC <= 400
    #       同时 P_AGC/N - 1 >= 0    =>  P_AGC >= 100
    #       所以 P_AGC 合理区间是 [100, 400]
    P_AGC = 300.0
    return V, P_AGC


# ============================================================
# 三、损伤模型（★真实版替换这里★）
# ============================================================
def damage_spindle(P, V):
    """
    主轴疲劳损伤 —— 占位模型

    【物理逻辑】
      风能过剩时，风速越高 → 可用风能越多 → 发同样功率越"轻松"，
      主轴承受的扭矩越小 → 损伤越小。
      损伤随功率呈非线性增长（工程上常用幂次关系）。

    【真实版替换为】
      Q1 的雨流计数损伤模型 + Q2 的主轴扭矩估算
      即：先由 (P, V) 估扭矩 T，再由 T 的时序用雨流法算累积损伤

    参数
    ----
    P : (N,) 各风机功率参考值 (MW)
    V : (N,) 各风机轮毂处风速 (m/s)

    返回
    ----
    (N,) 各台风机的损伤值（无量纲，越小越好）
    """
    # 风速有效因子：以额定风速为基准，风速越大单位功率损伤越小
    v_factor = (V_RATED / V) ** 2
    # 损伤 ∝ P³（疲劳损伤对载荷的典型幂次）
    return 1e-3 * (P ** 3) * v_factor


def damage_tower(P, V):
    """
    塔架疲劳损伤 —— 占位模型

    【物理逻辑】
      风推动风轮产生推力，风速越大推力越大 → 塔架受力越大；
      功率越大，风轮吸收的能量越多，剩余作用于塔架的推力也变化。

    【真实版替换为】
      Q1 的雨流计数损伤模型 + Q2 的塔架推力估算

    返回
    ----
    (N,) 各台风机的损伤值
    """
    # 风速越大，塔架受力越大
    v_factor = (V / V_RATED) ** 1.5
    # 塔架损伤 ∝ P^2.5
    return 8e-4 * (P ** 2.5) * v_factor


# ============================================================
# 四、损伤的"解析简化版"（★性能优化关键★）
# ============================================================
# 【为什么需要这个】
#   题目要求"每秒计算一次"，如果每次目标函数求值都要跑完整损伤模型，
#   速度会崩。所以把损伤函数对 P 做解析化处理——
#   观察到 D_spindle = a_i * P^3，D_tower = b_i * P^2.5
#   其中 a_i, b_i 只跟风速有关，与 P 无关。
#   于是预计算 a_i, b_i 后，每次求值只是两次幂运算，极快。
#
#   这就是本题"兼顾模型复杂度和精度"的体现方式之一。

def precompute_coeffs(V):
    """
    预计算每台风机与 P 无关的系数。

    返回
    ----
    a : (N,) 主轴损伤系数
    b : (N,) 塔架损伤系数
    """
    a = 1e-3 * (V_RATED / V) ** 2      # 对应 P^3 的系数
    b = 8e-4 * (V / V_RATED) ** 1.5    # 对应 P^2.5 的系数
    return a, b


